# build_courses.R — the course layer, generated from _data/courses.yml and
# _data/topics.yml.
#
# Writes
#   index.qmd                       home page: the four courses, then all
#                                   32 topics grouped by course
#   courses/<slug>/index.qmd        course page: outcomes, audience, topics
#   courses/<slug>/contents.qmd     every tutorial of the course, topic by
#                                   topic (Quarto table listings)
# and rewrites the hero kicker of every tutorials/<topic>/index.qmd so the
# topic page names its course.
#
# Run from the repository root:
#   Rscript R/build_courses.R           regenerate
#   Rscript R/build_courses.R --check   write nothing; fail if any generated
#                                       file is out of date or a topic is
#                                       missing from, or repeated in, a course

suppressPackageStartupMessages(library(yaml))

check_only <- "--check" %in% commandArgs(trailingOnly = TRUE)

topics <- yaml::read_yaml("_data/topics.yml")$topics
courses <- yaml::read_yaml("_data/courses.yml")$courses
topic_by_slug <- setNames(topics, vapply(topics, `[[`, "", "slug"))

# ---- validation ---------------------------------------------------------

assigned <- unlist(lapply(courses, `[[`, "topics"))
problems <- c(
  sprintf("topic '%s' is in more than one course", unique(assigned[duplicated(assigned)])),
  sprintf("topic '%s' is in no course", setdiff(names(topic_by_slug), assigned)),
  sprintf("course topic '%s' is not in _data/topics.yml", setdiff(assigned, names(topic_by_slug)))
)
if (length(problems)) stop(paste(c("_data/courses.yml:", problems), collapse = "\n  "), call. = FALSE)

# ---- helpers --------------------------------------------------------------

number_words <- c("one", "two", "three", "four", "five", "six", "seven", "eight",
                  "nine", "ten", "eleven", "twelve")
generated_note <- c(
  "# Generated by R/build_courses.R from _data/courses.yml and _data/topics.yml.",
  "# Edit those files, then run: Rscript R/build_courses.R"
)

q <- function(x) paste0('"', gsub('"', '\\\\"', x), '"')
course_count_chip <- function(course, unit = "TUTORIALS") {
  sprintf('<span class="count-chip"> · <span data-topic-sum="%s"></span> %s</span>',
          paste(course$topics, collapse = " "), unit)
}
topic_count_chip <- function(slug, unit = "tutorials") {
  sprintf('<span class="count-chip"> · <span data-topic-count="%s"></span> %s</span>', slug, unit)
}
course_label <- function(course) sprintf("Course %d — %s", course$number, course$title)

