# ---- course pages -----------------------------------------------------------

course_page <- function(cr) {
  others <- Filter(function(o) o$slug != cr$slug, courses)
  topic_cards <- unlist(lapply(seq_along(cr$topics), function(i) {
    slug <- cr$topics[[i]]
    tp <- topic_by_slug[[slug]]
    c("::: {.card}",
      "::: {.kicker}",
      sprintf("Topic %d%s", i, topic_count_chip(slug)),
      ":::",
      sprintf("### [%s](../../tutorials/%s/index.qmd)", tp$display, slug),
      tp$blurb,
      ":::",
      "")
  }))
  c("---",
    sprintf('title: "Course %d"', cr$number),
    sprintf("description: %s", q(cr$blurb)),
    "toc: true",
    "title-block-style: none",
    generated_note,
    "---",
    "",
    "::: {.hero}",
    "::: {.kicker}",
    sprintf("COURSE %d · %s · %d TOPICS%s", cr$number, toupper(cr$level),
            length(cr$topics), course_count_chip(cr)),
    ":::",
    sprintf("# %s", cr$title),
    "::: {.lead}",
    cr$lead,
    ":::",
    ":::",
    "",
    "## What you'll be able to do by the end",
    "",
    paste("-", unlist(cr$outcomes)),
    "",
    "## Who should take this course",
    "",
    cr$audience,
    "",
    sprintf("## The %s topics", number_words[length(cr$topics)]),
    "",
    "::: {.card-grid}",
    "",
    topic_cards,
    ":::",
    "",
    "## Contents",
    "",
    "[Every tutorial in this course, topic by topic →](contents.qmd)",
    "",
    "## The other courses",
    "",
    vapply(others, function(o) sprintf("- [%s](../%s/index.qmd) — %s",
                                       course_label(o), o$slug, o$blurb), ""),
    ""
  )
}

contents_page <- function(cr) {
  listings <- unlist(lapply(cr$topics, function(slug) c(
    sprintf("  - id: topic-%s", slug),
    sprintf('    contents: "../../tutorials/%s/*/index.qmd"', slug),
    "    type: table",
    "    fields: [title, description]",
    '    sort: "title"',
    "    sort-ui: false",
    "    filter-ui: false",
    "    page-size: 100"
  )))
  sections <- unlist(lapply(seq_along(cr$topics), function(i) {
    slug <- cr$topics[[i]]
    tp <- topic_by_slug[[slug]]
    c(sprintf("## Topic %d · %s {#%s}", i, tp$display, slug),
      "",
      sprintf("%s [Topic page →](../../tutorials/%s/index.qmd)", tp$blurb, slug),
      "",
      sprintf("::: {#topic-%s .course-contents}", slug),
      ":::",
      "")
  }))
  c("---",
    sprintf('title: "Course %d"', cr$number),
    sprintf("description: %s", q(sprintf("Every tutorial in %s, topic by topic.", course_label(cr)))),
    "toc: true",
    "title-block-style: none",
    generated_note,
    "listing:",
    listings,
    "---",
    "",
    "::: {.hero}",
    "::: {.kicker}",
    sprintf("COURSE %d · %s", cr$number, toupper(cr$title)),
    ":::",
    "# Contents",
    "::: {.lead}",
    "Every tutorial in the course, topic by topic. Within a topic the tutorials",
    "are listed alphabetically.",
    ":::",
    ":::",
    "",
    sprintf("[← Back to %s](index.qmd)", course_label(cr)),
    "",
    sections
  )
}

# ---- topic page kickers -----------------------------------------------------

kicker_line <- function(cr, position, slug) {
  sprintf('  <div class="kicker"><a href="../../courses/%s/">Course %d · %s</a> · Topic %d of %d%s</div>',
          cr$slug, cr$number, cr$title, position, length(cr$topics),
          topic_count_chip(slug, "TUTORIALS"))
}

topic_page <- function(path, cr, position, slug) {
  lines <- readLines(path, warn = FALSE, encoding = "UTF-8")
  hit <- grep('^\\s*<div class="kicker">.*</div>\\s*$', lines)
  if (length(hit) == 0) stop(sprintf("%s: no hero kicker line", path), call. = FALSE)
  lines[hit[1]] <- kicker_line(cr, position, slug)
  lines
}

# ---- write or check -----------------------------------------------------------

outputs <- list("index.qmd" = home_page())
for (cr in courses) {
  outputs[[sprintf("courses/%s/index.qmd", cr$slug)]] <- course_page(cr)
  outputs[[sprintf("courses/%s/contents.qmd", cr$slug)]] <- contents_page(cr)
  for (i in seq_along(cr$topics)) {
    slug <- cr$topics[[i]]
    path <- sprintf("tutorials/%s/index.qmd", slug)
    outputs[[path]] <- topic_page(path, cr, i, slug)
  }
}

stale <- character()
for (path in names(outputs)) {
  wanted <- paste0(paste(outputs[[path]], collapse = "\n"), "\n")
  current <- if (file.exists(path)) paste0(paste(readLines(path, warn = FALSE, encoding = "UTF-8"), collapse = "\n"), "\n") else NA
  if (identical(current, wanted)) next
  stale <- c(stale, path)
  if (!check_only) {
    dir.create(dirname(path), recursive = TRUE, showWarnings = FALSE)
    con <- file(path, open = "w", encoding = "UTF-8")
    writeLines(outputs[[path]], con)
    close(con)
  }
}

# The navbar's Courses and Topics menus in _quarto.yml are written by hand;
# they must list the courses and the topics in the order of courses.yml.
nav_left <- yaml::read_yaml("_quarto.yml")$website$navbar$left
menu_hrefs <- function(label) {
  for (item in nav_left) {
    if (identical(item$text, label)) {
      return(unlist(lapply(item$menu, function(m) m$href)))
    }
  }
  character()
}
known <- vapply(courses, `[[`, "", "slug")
hand_edits <- character()
if (!identical(menu_hrefs("Courses"), c(sprintf("courses/%s/index.qmd", known), "tutorials.qmd"))) {
  hand_edits <- c(hand_edits, "_quarto.yml: navbar Courses menu does not match _data/courses.yml")
}
if (!identical(menu_hrefs("Topics"), sprintf("tutorials/%s/index.qmd", assigned))) {
  hand_edits <- c(hand_edits, "_quarto.yml: navbar Topics menu does not match _data/courses.yml")
}

# Course directories that no longer correspond to a course.
orphans <- setdiff(basename(list.dirs("courses", recursive = FALSE)), known)
if (length(orphans)) {
  hand_edits <- c(hand_edits, sprintf("courses/%s/ is not a course in _data/courses.yml; remove it", orphans))
}

if (check_only) {
  if (length(stale) || length(hand_edits)) {
    stop(paste(c("The course layer is out of date.",
                 if (length(stale)) c("Regenerate with Rscript R/build_courses.R:", stale),
                 if (length(hand_edits)) c("Fix by hand:", hand_edits)),
               collapse = "\n  "), call. = FALSE)
  }
  cat(sprintf("Course layer up to date: %d courses, %d topics, %d generated files\n",
              length(courses), length(topics), length(outputs)))
} else {
  cat(sprintf("Wrote %d of %d generated files\n", length(stale), length(outputs)))
  if (length(hand_edits)) warning(paste(c("Fix by hand:", hand_edits), collapse = "\n  "), call. = FALSE)
}
